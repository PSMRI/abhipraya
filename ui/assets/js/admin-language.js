  function translateText(root = document.body) {
    if (language !== 'hi' || !root) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach((node) => {
      const original = node.nodeValue;
      const key = original.trim();
      if (!hindi[key]) return;
      node.nodeValue = original.replace(key, hindi[key]);
    });
    root.querySelectorAll?.('[placeholder],[title],[aria-label]').forEach((element) => {
      ['placeholder', 'title', 'aria-label'].forEach((attribute) => {
        const value = element.getAttribute(attribute);
        if (value && hindi[value]) element.setAttribute(attribute, hindi[value]);
      });
    });
  }

  function addSelector() {
    const actions = document.querySelector('.header-actions, .feedback-header-actions, .ab-topbar');
    if (!actions || actions.querySelector('[data-admin-language]')) return;
    const toggle = document.createElement('button');
    toggle.type = 'button';
    toggle.className = 'admin-language-icon';
    toggle.title = language === 'hi' ? 'Switch to English' : 'हिन्दी में बदलें';
    toggle.setAttribute('aria-label', toggle.title);
    toggle.innerHTML = '<i class="bi bi-translate" aria-hidden="true"></i>';
    toggle.addEventListener('click', () => {
      localStorage.setItem(storageKey, language === 'hi' ? 'en' : 'hi');
      window.location.reload();
    });
    actions.prepend(toggle);
  }

  document.documentElement.lang = language;
  addSelector();
  translateText();
  if (language === 'hi') {
    new MutationObserver((records) => records.forEach((record) =>
      record.addedNodes.forEach((node) => {
        if (node.nodeType === Node.ELEMENT_NODE) translateText(node);
      })
    )).observe(document.body, { childList: true, subtree: true });
  }
